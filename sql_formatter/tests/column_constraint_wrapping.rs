#[macro_use]
mod helper;

#[test]
fn format_many_column_constraints_continue_on_an_indented_line() {
    assert_fmt_eq!(
        r#"--
create table accounts (id int generated by default as identity (start with 1 increment by 1 minvalue 1 maxvalue 9223372036854775807 cache 1) not null primary key unique check (id > 0) references other (id))
"#,
        r#"--
create table accounts (
	id int generated by default as identity (start with 1 increment by 1 minvalue 1 maxvalue 9223372036854775807 cache 1)
		not null primary key unique check (id > 0) references other (id)
)
"#
    );
}

#[test]
fn format_long_check_on_the_column_line_wraps_inside_its_parentheses() {
    assert_fmt_eq!(
        r#"--
create table accounts (amount int check (amount > 0 and amount < 100 and amount <> 5 and amount <> 7 and amount <> 9 and amount <> 11 and amount <> 13 and amount <> 15))
"#,
        r#"--
create table accounts (
	amount int check (
		amount > 0
			and amount < 100
			and amount <> 5
			and amount <> 7
			and amount <> 9
			and amount <> 11
			and amount <> 13
			and amount <> 15
	)
)
"#
    );
}

#[test]
fn format_long_check_on_a_continuation_line_stays_aligned_with_it() {
    assert_fmt_eq!(
        r#"--
create table accounts (amount int not null default 0 unique references other (id) check (amount > 0 and amount < 100 and amount <> 5 and amount <> 7 and amount <> 9 and amount <> 11))
"#,
        r#"--
create table accounts (
	amount int not null default 0 unique references other (id)
		check (
			amount > 0
				and amount < 100
				and amount <> 5
				and amount <> 7
				and amount <> 9
				and amount <> 11
		)
)
"#
    );
}

#[test]
fn format_long_table_check_wraps_inside_its_parentheses() {
    assert_fmt_eq!(
        r#"--
create table accounts (id int, check (amount > 0 and amount < 100 and amount <> 5 and amount <> 7 and amount <> 9 and amount <> 11 and amount <> 13 and amount <> 15))
"#,
        r#"--
create table accounts (
	id int,
	check (
		amount > 0
			and amount < 100
			and amount <> 5
			and amount <> 7
			and amount <> 9
			and amount <> 11
			and amount <> 13
			and amount <> 15
	)
)
"#
    );
}

#[test]
fn format_long_sequence_options_wrap_inside_their_parentheses() {
    assert_fmt_eq!(
        r#"--
create table accounts (identifier bigint generated always as identity (start with 1000000000 increment by 1000000 minvalue 1000000000 maxvalue 9223372036854775807 cache 1000000))
"#,
        r#"--
create table accounts (
	identifier bigint generated always as identity (
		start with 1000000000 increment by 1000000 minvalue 1000000000 maxvalue 9223372036854775807 cache 1000000
	)
)
"#
    );
}

#[test]
fn format_short_check_and_constraints_stay_on_one_line() {
    assert_fmt!(
        r#"--
create table accounts (amount int not null check (amount > 0) references other (id))
"#
    );
}
